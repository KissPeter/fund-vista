"""CLI: STL mesh -> side-view plotter artwork SVG.

    python -m backend.penplot.stl2plot knipexXs.stl -o knipex-side.svg
    python -m backend.penplot.stl2plot models/ --out-dir svg/ --report svg/report.json

The side view is generated by ``slice3d`` cross-sections along the mesh's
longest axis. Every output is artwork only (paths, no text and no images), so
it can be sent straight to ``POST /v1/compose-sheet`` with ``artwork: "inline"``.
Sheet furniture is composed there and nowhere else (AGENTS.md).

Batch use mirrors ``img2plot``: several inputs (or a folder) need
``--out-dir``; ``--report`` writes one JSON record per STL,
``--skip-existing`` makes reruns resumable, ``--jobs N`` runs N meshes at
once, and a bad file does not stop the rest. Exit codes: 0 ok, 1 some
failed, 2 usage/validation error.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

from backend.penplot import stl_views

EXIT_OK, EXIT_FAILED, EXIT_USAGE = 0, 1, 2
STL_EXTS = (".stl",)


def expand_sources(srcs: list[str]) -> list[str]:
    """Files as given; a folder becomes its STL files (sorted, not recursive)."""
    out: list[str] = []
    for src in srcs:
        if os.path.isdir(src):
            out.extend(
                os.path.join(src, name) for name in sorted(os.listdir(src))
                if name.lower().endswith(STL_EXTS))
        else:
            out.append(src)
    return out


def stem_of(src: str) -> str:
    return Path(src).stem or "model"


def plan_outputs(srcs: list[str], out_dir: str | None, out: str | None) -> list[tuple[str, str]]:
    if out_dir:
        return [(src, os.path.join(out_dir, f"{stem_of(src)}.svg")) for src in srcs]
    if len(srcs) == 1:
        return [(srcs[0], out or f"{stem_of(srcs[0])}.svg")]
    raise ValueError("several inputs need --out-dir")


def process_one(src: str, out: str, argd: dict) -> dict:
    """Render one mesh; never raises, so a batch survives a bad STL."""
    started = time.perf_counter()
    rec: dict = {"src": src, "out": out, "status": "error"}
    try:
        kwargs = {
            key: argd[key]
            for key in ("slices", "fit_mm", "stroke_mm", "margin_mm")
        }
        svg = stl_views.render_side_view(src, **kwargs)
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        tmp = f"{out}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(svg)
        os.replace(tmp, out)  # a killed run never leaves a half-written SVG
        rec.update(status="ok", strokes=svg.count("<path "), warnings=[])
    except Exception as exc:  # noqa: BLE001 - reported, batch continues
        rec["error"] = f"{type(exc).__name__}: {exc}"
    rec["seconds"] = round(time.perf_counter() - started, 2)
    return rec


def make_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", nargs="+", help="STL file or folder (repeatable)")
    ap.add_argument("-o", "--out", help="output artwork SVG (single input only)")
    ap.add_argument("--out-dir", help="output folder (required for several inputs)")
    ap.add_argument("--report", help="write a JSON report (one record per STL)")
    ap.add_argument("--jobs", type=int, default=1, help="meshes rendered at once (default 1)")
    ap.add_argument("--skip-existing", action="store_true",
                    help="skip meshes whose SVG exists and is newer than the STL")
    ap.add_argument("--fail-fast", action="store_true", help="stop at the first failure")
    ap.add_argument("-q", "--quiet", action="store_true", help="no per-mesh progress lines")
    ap.add_argument("--slices", type=int, default=stl_views.DEFAULT_SLICES,
                    help=f"slices along the longest axis (default {stl_views.DEFAULT_SLICES})")
    ap.add_argument("--fit-mm", type=float, default=stl_views.DEFAULT_FIT_MM,
                    help=f"largest side-view extent in mm (default {stl_views.DEFAULT_FIT_MM})")
    ap.add_argument("--margin-mm", type=float, default=stl_views.DEFAULT_MARGIN_MM,
                    help=f"clearance around the artwork (default {stl_views.DEFAULT_MARGIN_MM})")
    ap.add_argument("--stroke-mm", type=float, default=stl_views.DEFAULT_STROKE_MM,
                    help=f"pen width (default {stl_views.DEFAULT_STROKE_MM})")
    return ap


def _line(i: int, n: int, rec: dict) -> str:
    name = os.path.basename(rec["out"])
    if rec["status"] == "ok":
        return f"[{i}/{n}] ok    {name}  {rec['strokes']} strokes  {rec['seconds']}s"
    return f"[{i}/{n}] FAIL  {os.path.basename(rec['src'])}  {rec['error']}"


def main(argv=None) -> int:
    ap = make_parser()
    a = ap.parse_args(argv)
    try:
        plan = plan_outputs(expand_sources(a.src), a.out_dir, a.out)
    except ValueError as exc:
        ap.error(str(exc))
    if not plan:
        ap.error("no STL files found")
    if a.jobs < 1:
        ap.error("--jobs must be >= 1")
    if (a.slices < 1 or a.fit_mm <= 0 or a.margin_mm < 0 or a.stroke_mm <= 0):
        ap.error("invalid geometry options (slices >= 1, fit/stroke > 0, margin >= 0)")

    argd = vars(a)
    todo: list[tuple[str, str]] = []
    records: list[dict] = []
    for src, out in plan:
        if (a.skip_existing and os.path.exists(out)
                and os.path.getmtime(out) >= os.path.getmtime(src)):
            records.append({"src": src, "out": out, "status": "skipped",
                            "strokes": None, "seconds": 0.0, "warnings": []})
        else:
            todo.append((src, out))

    n, done = len(todo), 0

    def finish(rec: dict) -> bool:
        nonlocal done
        done += 1
        records.append(rec)
        if not a.quiet:
            print(_line(done, n, rec), file=sys.stderr, flush=True)
        return rec["status"] == "ok" or not a.fail_fast

    t0 = time.perf_counter()
    if a.jobs == 1 or n <= 1:
        for src, out in todo:
            if not finish(process_one(src, out, argd)):
                break
    else:
        with ProcessPoolExecutor(max_workers=min(a.jobs, n)) as pool:
            futures = [pool.submit(process_one, s, o, argd) for s, o in todo]
            for fut in as_completed(futures):
                if not finish(fut.result()):
                    for f in futures:
                        f.cancel()
                    break

    failed = [r for r in records if r["status"] == "error"]
    skipped = sum(r["status"] == "skipped" for r in records)
    summary = {"total": len(plan), "ok": sum(r["status"] == "ok" for r in records),
               "failed": len(failed), "skipped": skipped,
               "seconds": round(time.perf_counter() - t0, 1)}
    if a.report:
        os.makedirs(os.path.dirname(os.path.abspath(a.report)), exist_ok=True)
        with open(a.report, "w", encoding="utf-8") as fh:
            json.dump({"summary": summary, "results": sorted(records, key=lambda r: r["src"])},
                      fh, indent=2)
    print(f"{summary['ok']} ok, {summary['failed']} failed, {skipped} skipped "
          f"of {summary['total']} in {summary['seconds']}s", file=sys.stderr)
    return EXIT_FAILED if failed else EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
